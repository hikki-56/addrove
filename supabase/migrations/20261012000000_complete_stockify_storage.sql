create table if not exists production_jobs (
  job_id text primary key,
  job_no text not null unique,
  production_date date not null,
  status text not null check (status in ('DRAFT','WAITING','IN_PROGRESS','COMPLETED','CANCELLED')),
  table_no integer not null check (table_no between 1 and 5),
  priority text not null check (priority in ('NORMAL','URGENT','CRITICAL')),
  product_id text not null references products(product_id),
  sku text not null,
  product_name text not null,
  unit text not null,
  target_qty numeric(14,3) not null check (target_qty > 0),
  note text not null default '',
  location text not null default '',
  created_by text not null,
  created_by_name text not null default '',
  created_at timestamptz not null default now(),
  submitted_at timestamptz,
  started_by_name text not null default '',
  started_at timestamptz,
  completed_at timestamptz,
  cancelled_at timestamptz,
  cancelled_by_name text not null default '',
  cancel_reason text not null default '',
  close_reason text not null default '',
  reopen_reason text not null default '',
  reopen_count integer not null default 0 check (reopen_count >= 0),
  updated_at timestamptz not null default now()
);
create index if not exists production_jobs_date_status_idx on production_jobs(production_date,status);

create table if not exists production_reports (
  report_id text primary key,
  job_no text not null references production_jobs(job_no),
  report_no integer not null check (report_no > 0),
  kind text not null check (kind in ('REPORT','ADJUSTMENT')),
  report_kind text not null default '' check (report_kind in ('','PARTIAL','FINAL')),
  good_qty numeric(14,3) not null,
  defect_qty numeric(14,3) not null,
  defect_cause text not null default '',
  reason text not null default '',
  note text not null default '',
  photo_url text not null default '',
  reported_by text not null,
  reported_by_name text not null default '',
  reported_at timestamptz not null default now(),
  cumulative_good numeric(14,3) not null check (cumulative_good >= 0),
  cumulative_defect numeric(14,3) not null check (cumulative_defect >= 0),
  idempotency_key text not null unique check (idempotency_key <> ''),
  unique (job_no, report_no),
  check (kind <> 'REPORT' or (good_qty >= 0 and defect_qty >= 0 and report_kind <> '')),
  check (kind <> 'ADJUSTMENT' or btrim(reason) <> '')
);
create index if not exists production_reports_job_idx on production_reports(job_no,reported_at);

create table if not exists production_history (
  history_id text primary key,
  job_no text not null references production_jobs(job_no),
  action text not null,
  actor_id text not null,
  actor_name text not null default '',
  at timestamptz not null default now(),
  reason text not null default '',
  detail text not null default '{}'
);
create index if not exists production_history_job_idx on production_history(job_no,at);

create table if not exists production_notifications (
  notif_id text primary key,
  target_role text not null check (target_role in ('ADMIN','APPROVER')),
  job_no text not null references production_jobs(job_no),
  message text not null,
  created_at timestamptz not null default now(),
  created_by_name text not null default '',
  read_by jsonb not null default '[]'::jsonb check (jsonb_typeof(read_by) = 'array')
);

-- Retain auxiliary Express/Q/warehouse and historical tabs without losing columns.
create table if not exists storage_tabs (
  tab_id bigint generated by default as identity primary key,
  name text not null unique,
  headers jsonb not null default '[]'::jsonb,
  source_name text,
  updated_at timestamptz not null default now()
);
create table if not exists storage_rows (
  tab_id bigint not null references storage_tabs(tab_id),
  row_no integer not null check (row_no >= 2),
  cells jsonb not null check (jsonb_typeof(cells) = 'array'),
  primary key(tab_id,row_no)
);
create table if not exists migration_snapshots (
  snapshot_id text primary key,
  source_id text not null,
  checksum text not null,
  manifest jsonb not null,
  verified_at timestamptz,
  created_at timestamptz not null default now()
);
create table if not exists document_sequences (
  document_type text primary key,
  last_value bigint not null default 0
);

-- Stable positions are only for old integration code; native repositories use IDs.
do $$
declare tbl text;
begin
  foreach tbl in array array['warehouses','locations','shelves','products','users','documents',
    'stock_movements','stock_summary','stock_counts','idempotency_records','audit_logs','operation_journal',
    'login_logs','bom_formulas','bom_formula_items','production_jobs','production_reports',
    'production_history','production_notifications']
  loop
    execute format('alter table public.%I add column if not exists source_row bigint generated by default as identity (start with 2)', tbl);
    execute format('alter table public.%I add column if not exists source_cells jsonb', tbl);
    execute format('create unique index if not exists %I on public.%I(source_row)', tbl || '_source_row_idx', tbl);
    execute format('alter table public.%I enable row level security', tbl);
  end loop;
end $$;
alter table storage_tabs enable row level security;
alter table storage_rows enable row level security;
alter table migration_snapshots enable row level security;
alter table document_sequences enable row level security;

create or replace function stockify_prevent_report_mutation() returns trigger
language plpgsql set search_path = public as $$
begin
  raise exception 'Production reports are immutable; append an adjustment instead';
end $$;
drop trigger if exists production_reports_immutable on production_reports;
create trigger production_reports_immutable before update or delete on production_reports
for each row execute function stockify_prevent_report_mutation();

